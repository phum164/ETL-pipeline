CREATE OR REPLACE FUNCTION etl.business_date(p_at TIMESTAMPTZ)
RETURNS DATE
LANGUAGE SQL
STABLE
RETURNS NULL ON NULL INPUT
AS $$
  SELECT (p_at AT TIME ZONE 'Asia/Bangkok')::DATE;
$$;

CREATE OR REPLACE FUNCTION etl.date_key(p_at TIMESTAMPTZ)
RETURNS INTEGER
LANGUAGE SQL
STABLE
RETURNS NULL ON NULL INPUT
AS $$
  SELECT TO_CHAR(etl.business_date(p_at), 'YYYYMMDD')::INTEGER;
$$;


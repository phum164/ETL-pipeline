CREATE OR REPLACE FUNCTION etl.ensure_dates(p_dates DATE[])
RETURNS VOID
LANGUAGE SQL
AS $$
  INSERT INTO dw.dim_date (
    date_key, calendar_date, calendar_year, calendar_quarter, calendar_month,
    month_name, week_of_year, week_start_date, day_of_month, iso_day_of_week, is_weekend
  )
  SELECT
    TO_CHAR(d, 'YYYYMMDD')::INTEGER,
    d,
    EXTRACT(YEAR FROM d)::SMALLINT,
    EXTRACT(QUARTER FROM d)::SMALLINT,
    EXTRACT(MONTH FROM d)::SMALLINT,
    TO_CHAR(d, 'FMMonth'),
    EXTRACT(WEEK FROM d)::SMALLINT,
    DATE_TRUNC('week', d)::DATE,
    EXTRACT(DAY FROM d)::SMALLINT,
    EXTRACT(ISODOW FROM d)::SMALLINT,
    EXTRACT(ISODOW FROM d) IN (6, 7)
  FROM (
    SELECT DISTINCT unnest(p_dates) AS d
  ) AS dates
  WHERE d IS NOT NULL
  ON CONFLICT (date_key) DO NOTHING;
$$;


CREATE OR REPLACE FUNCTION etl.backfill_customer_dimension()
RETURNS void
LANGUAGE plpgsql
AS $$
BEGIN
  WITH latest_customer AS (
    SELECT DISTINCT ON (source_system, buyer_source_id)
      source_system,
      buyer_source_id AS customer_source_id,
      buyer_name AS customer_name,
      province_name AS latest_province_name,
      postal_code AS latest_postal_code,
      source_updated_at,
      last_loaded_batch_id
    FROM dw.fact_order
    WHERE buyer_source_id IS NOT NULL
    ORDER BY source_system, buyer_source_id, source_updated_at DESC, order_source_id DESC
  )
  INSERT INTO dw.dim_customer (
    source_system, customer_source_id, customer_name, latest_province_name,
    latest_postal_code, source_updated_at, last_loaded_batch_id
  )
  SELECT
    source_system, customer_source_id, customer_name, latest_province_name,
    latest_postal_code, source_updated_at, last_loaded_batch_id
  FROM latest_customer
  ON CONFLICT (source_system, customer_source_id) DO UPDATE SET
    customer_name = EXCLUDED.customer_name,
    latest_province_name = EXCLUDED.latest_province_name,
    latest_postal_code = EXCLUDED.latest_postal_code,
    source_updated_at = EXCLUDED.source_updated_at,
    last_loaded_batch_id = EXCLUDED.last_loaded_batch_id
  WHERE EXCLUDED.source_updated_at >= dw.dim_customer.source_updated_at;

  UPDATE dw.fact_order AS orders
  SET customer_key = customers.customer_key
  FROM dw.dim_customer AS customers
  WHERE customers.source_system = orders.source_system
    AND customers.customer_source_id = orders.buyer_source_id
    AND orders.customer_key IS DISTINCT FROM customers.customer_key;
END;
$$;

SELECT etl.backfill_customer_dimension();

UPDATE dw.fact_order SET customer_key = 0 WHERE customer_key IS NULL;
ALTER TABLE dw.fact_order ALTER COLUMN customer_key SET DEFAULT 0;
ALTER TABLE dw.fact_order ALTER COLUMN customer_key SET NOT NULL;

DO $$
BEGIN
  IF NOT EXISTS (
    SELECT 1
    FROM pg_constraint
    WHERE conrelid = 'dw.fact_order'::regclass
      AND conname = 'fact_order_customer_key_fkey'
  ) THEN
    ALTER TABLE dw.fact_order
      ADD CONSTRAINT fact_order_customer_key_fkey
      FOREIGN KEY (customer_key) REFERENCES dw.dim_customer(customer_key);
  END IF;
END;
$$;

